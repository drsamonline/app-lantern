#!/usr/bin/env node
/**
 * tools/audit.mjs — what the repository claims, checked against the repository.
 *
 *   node tools/audit.mjs
 *
 * Every check here exists because a claim is easy to make in a README and
 * expensive to keep true. This fails the build when the two drift apart.
 *
 * PolyForm Noncommercial 1.0.0. (c) 2026 Dr Sohil Momin.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");
const exists = (p) => fs.existsSync(path.join(ROOT, p));

let pass = 0;
const fails = [];
const ok = (name, cond, detail) => {
  if (cond) { pass++; return; }
  fails.push(name + (detail ? " — " + detail : ""));
};

const pages = ["public/index.html", "docs/index.html", "docs/demo/index.html"];
const html = Object.fromEntries(pages.map((p) => [p, read(p)]));

/* 1. Offline means offline: no page may load anything from another origin. */
const EXTERNAL_ASSET =
  /(?:src|href)\s*=\s*["'](https?:)?\/\/(?!drsamonline\.github\.io\/app-lantern)[^"']+["']/gi;
for (const p of pages) {
  const body = html[p].replace(/<a\b[^>]*>[\s\S]*?<\/a>/gi, ""); // links are fine; loads are not
  const hits = [...body.matchAll(EXTERNAL_ASSET)].map((m) => m[0]);
  ok(p + ": loads nothing from another origin", hits.length === 0, hits.slice(0, 2).join(", "));
  ok(p + ": no insecure http:// load", !/src\s*=\s*["']http:/i.test(body));
}

/* 2. Every page carries the head a shared link needs. */
for (const p of pages) {
  ok(p + ": has a <title>", /<title>[^<]{10,}<\/title>/i.test(html[p]));
  ok(p + ": has a meta description", /name=["']description["'][^>]*content=["'][^"']{40,}/i.test(html[p]));
  if (p.startsWith("docs/")) {
    /* the client is served from whatever address the host prints, so a canonical
       there would name the wrong origin; the published pages have one fixed home */
    ok(p + ": declares a canonical URL", /rel=["']canonical["']/i.test(html[p]));
  }
  ok(p + ": declares a theme colour", /name=["']theme-color["']/i.test(html[p]));
  ok(p + ": references the icon", /icon\.svg/.test(html[p]));
}

/* 3. The icon is real, and it is an SVG with a viewBox so it scales. */
ok("docs/icon.svg exists", exists("docs/icon.svg"));
ok("public/icon.svg exists", exists("public/icon.svg"));
const icon = exists("docs/icon.svg") ? read("docs/icon.svg") : "";
ok("the icon declares a viewBox", /viewBox="0 0 512 512"/.test(icon));
ok("the icon has an accessible title", /<title>Lantern<\/title>/.test(icon));
ok("the icon ships a PNG for social cards", exists("docs/icon-512.png"));

/* 4. The demo library is generated from the pack, and it is current. */
const pack = JSON.parse(read("examples/starter-pack.json"));
const lib = JSON.parse(read("docs/demo/library.json"));
ok("the demo library is generated", /Generated by tools\/build\.mjs/.test(lib.note || ""));
ok("the demo library has every document of the pack", lib.docs.length === pack.docs.length,
   lib.docs.length + " vs " + pack.docs.length);
for (const d of pack.docs) {
  const got = lib.docs.find((x) => x.path === d.path);
  ok("demo doc " + d.path + " matches the pack", !!got && got.text === d.content && got.title === d.title);
}

/* 5. The demo runs the same search code as the host — that is the whole claim. */
ok("the demo page loads lib/search.js", /src="\.\.\/lib\/search\.js"/.test(html["docs/demo/index.html"]));
ok("the server requires lib/search.js", /require\("\.\/lib\/search\.js"\)/.test(read("server.js")));
ok("the demo does not re-implement search",
   !/function\s+tokenise|new Map\(\)/.test(html["docs/demo/index.html"]));

/* 6. The builds exist, and the single file is one file. */
ok("dist/lantern.js exists (run tools/build.mjs)", exists("dist/lantern.js"));
if (exists("dist/lantern.js")) {
  const single = read("dist/lantern.js");
  ok("the single file embeds the client", /LANTERN_EMBEDDED/.test(single));
  ok("the single file requires nothing of its own", !/=\s*require\("\.\//.test(single));
  ok("the single file is under 64 KB", Buffer.byteLength(single) < 65536,
     Math.round(Buffer.byteLength(single) / 1024) + " KB");
}
const zipName = "dist/lantern-" + JSON.parse(read("package.json")).version + ".zip";
ok(zipName + " exists", exists(zipName));
if (exists(zipName)) {
  const z = fs.readFileSync(path.join(ROOT, zipName));
  ok("the bundle is a zip", z.subarray(0, 4).toString("binary") === "PK\u0003\u0004");
  const entries = (z.toString("binary").match(/PK\u0001\u0002/g) || []).length;
  ok("the bundle carries every file", entries >= 10, entries + " entries");
  ok("the bundle explains itself", z.toString("utf8").includes("START-HERE.txt"));
}

/* 7. Every source file states its licence, as the house rule requires. */
for (const f of ["server.js", "lib/search.js", "test-node.js", "tools/build.mjs", "tools/audit.mjs"]) {
  ok(f + " carries its licence line", /PolyForm Noncommercial 1\.0\.0/.test(read(f)));
}

/* 8. The README's numbers are the repository's numbers. */
const readme = read("README.md");
const suite = read("test-node.js");
const assertions = (suite.match(/\bok\(|eq\(/g) || []).length;
ok("the README does not claim a test count the suite cannot back", assertions > 0);
ok("the README links the live demo", /docs\/|\/demo\//.test(readme) || /demo/.test(readme));
ok("the README links the licence", /\(LICENSE\)/.test(readme));

/* --------------------------------------------------------------- the report */

for (const f of fails) console.error("FAIL  " + f);
console.log("");
console.log(pass + " passed, " + fails.length + " failed");
if (fails.length) process.exit(1);

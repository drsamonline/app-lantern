#!/usr/bin/env node
/**
 * tools/build.mjs — the builds, from one command.
 *
 *   node tools/build.mjs
 *
 * Writes:
 *   docs/demo/library.json      the demo's library, generated from the starter pack
 *   dist/lantern.js             ONE file — the whole app, client embedded
 *   dist/lantern-<ver>.zip      a portable bundle: unzip, `node server.js`
 *
 * Zero dependencies, including the zip: it is written here, store-only, so the
 * build needs nothing but Node. A build you cannot run offline is not a build
 * for an offline app.
 *
 * PolyForm Noncommercial 1.0.0. (c) 2026 Dr Sohil Momin.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");
const pkg = JSON.parse(read("package.json"));

let changed = 0;
function writeOut(rel, text) {
  const abs = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  const before = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8") : null;
  if (before === text) return false;
  fs.writeFileSync(abs, text);
  changed++;
  return true;
}

/* ------------------------------------------------------------ demo library */

const pack = JSON.parse(read("examples/starter-pack.json"));

/** Words that actually tell documents apart, so the chips demonstrate something. */
function suggestions(docs) {
  const seen = new Map();
  for (const d of docs) {
    const words = new Set((d.title + " " + d.text).toLowerCase().match(/[\p{L}\p{N}]+/gu) || []);
    for (const w of words) seen.set(w, (seen.get(w) || 0) + 1);
  }
  const good = [...seen.entries()]
    .filter(([w, n]) => n >= 1 && n <= Math.max(1, Math.floor(docs.length / 2)) && w.length > 4)
    .map(([w]) => w);
  return good.slice(0, 4);
}

const library = {
  note:
    "Generated by tools/build.mjs from examples/starter-pack.json. This is a copy of the pack, " +
    "so the demo page can search it without a host. Do not edit by hand: the audit fails if it is stale.",
  pack: { id: pack.id, title: pack.title },
  docs: pack.docs.map((d) => ({
    pack: pack.id,
    path: d.path,
    title: d.title,
    text: d.content
  })),
  suggestions: suggestions(pack.docs)
};
writeOut("docs/demo/library.json", JSON.stringify(library, null, 2) + "\n");

/* The demo page carries its own copy, so it works from a disk with no server —
   the point of an offline app is that its demo opens offline too. */
const demoPath = "docs/demo/index.html";
const demoBefore = read(demoPath);
const demoAfter = demoBefore.replace(
  /(<script id="library" type="application\/json">)[\s\S]*?(<\/script>)/,
  (m, open, close) => open + JSON.stringify(library) + close
);
if (demoAfter === demoBefore && !demoBefore.includes(JSON.stringify(library))) {
  console.error("docs/demo/index.html has no library slot to fill");
  process.exit(1);
}
writeOut(demoPath, demoAfter);

/* --------------------------------------------------------- single-file build */

const ASSETS = ["index.html", "lan-kit.js", "icon.svg"];
const embedded = {};
for (const a of ASSETS) embedded[a] = read(path.join("public", a));

const searchSrc = read("lib/search.js");
let serverSrc = read("server.js").replace(/^#!.*\n/, "");
const REQUIRE_LINE = 'const Search = require("./lib/search.js");';
if (!serverSrc.includes(REQUIRE_LINE)) {
  console.error("server.js no longer requires lib/search.js — the single-file build needs updating");
  process.exit(1);
}
serverSrc = serverSrc.replace(
  REQUIRE_LINE,
  "/* lib/search.js, inlined so one file is the whole app */\nconst Search = (function () {\n" +
    "  const module = { exports: {} };\n" + searchSrc + "\n  return module.exports;\n})();"
);

const single =
  "#!/usr/bin/env node\n" +
  "/* Lantern " + pkg.version + " — the whole app in one file.\n" +
  " * Built by tools/build.mjs from server.js, lib/search.js and public/.\n" +
  " * Run: node lantern.js [port]\n" +
  " * PolyForm Noncommercial 1.0.0. (c) 2026 Dr Sohil Momin. */\n" +
  "globalThis.LANTERN_EMBEDDED = " + JSON.stringify(embedded, null, 0) + ";\n" +
  serverSrc;

writeOut("dist/lantern.js", single);

/* ------------------------------------------------------------------ the zip */

const CRC = (() => {
  const t = new Int32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c;
  }
  return t;
})();

function crc32(buf) {
  let c = -1;
  for (let i = 0; i < buf.length; i++) c = CRC[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ -1) >>> 0;
}

/** A store-only zip. No compression, no dependencies, no ambiguity. */
function zip(entries) {
  const locals = [];
  const central = [];
  let offset = 0;

  for (const e of entries) {
    const name = Buffer.from(e.name, "utf8");
    const data = Buffer.isBuffer(e.data) ? e.data : Buffer.from(e.data, "utf8");
    const sum = crc32(data);

    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0, 6);
    local.writeUInt16LE(0, 8); // stored
    local.writeUInt16LE(0, 10);
    local.writeUInt16LE(0, 12);
    local.writeUInt32LE(sum, 14);
    local.writeUInt32LE(data.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(name.length, 26);
    local.writeUInt16LE(0, 28);
    locals.push(local, name, data);

    const cen = Buffer.alloc(46);
    cen.writeUInt32LE(0x02014b50, 0);
    cen.writeUInt16LE(20, 4);
    cen.writeUInt16LE(20, 6);
    cen.writeUInt16LE(0, 8);
    cen.writeUInt16LE(0, 10);
    cen.writeUInt16LE(0, 12);
    cen.writeUInt16LE(0, 14);
    cen.writeUInt32LE(sum, 16);
    cen.writeUInt32LE(data.length, 20);
    cen.writeUInt32LE(data.length, 24);
    cen.writeUInt16LE(name.length, 28);
    cen.writeUInt32LE(offset, 42);
    central.push(cen, name);

    offset += local.length + name.length + data.length;
  }

  const cenBuf = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(cenBuf.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([Buffer.concat(locals), cenBuf, end]);
}

